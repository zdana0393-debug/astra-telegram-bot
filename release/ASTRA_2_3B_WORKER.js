function channelName(env) {
  const s=String(env.CHANNEL_USERNAME||'').trim();
  return /^@[A-Za-z0-9_]{5,32}$/.test(s) ? s : null;
}
async function channelMenu(env,id) {
  const c=channelName(env);
  if (!c) return send(env,id,"Канал пока не подключён. Прогнозы, карта дня и остальные доступные функции работают без подписки.");
  return send(env,id,`Канал ${c}\n\nЗа первую подтверждённую подписку начисляется +5 ✨. Откройте канал, затем выполните проверку.`,{
    reply_markup:{inline_keyboard:[
      [{text:"Открыть канал",url:`https://t.me/${c.slice(1)}`}],
      [{text:"Проверить подписку",callback_data:'channel:check'}],
    ]},
  });
}
async function channelCheck(env,id) {
  const c=channelName(env);
  if (!c) return channelMenu(env,id);
  const u=await getUser(env,id);
  if (u.channel_rewarded) return send(env,id,"Начисление за подписку уже проведено. Повторная проверка не меняет баланс.");
  let member;
  try { member=await tg(env,'getChatMember',{chat_id:c,user_id:id}); }
  catch(e){console.error('Channel check failed');return send(env,id,"Проверка подписки недоступна. Для неё боту нужны права администратора канала; повторите запрос позднее.");}
  const ok=['member','administrator','creator'].includes(member.status) || (member.status==='restricted'&&member.is_member===true);
  if (!ok) return send(env,id,"Подписка не подтверждена. После вступления в канал повторите проверку.");
  const r=await env.DB.prepare(`INSERT OR IGNORE INTO astra_operations(operation_id,telegram_id,reason,delta)
    VALUES(?,?,'channel',5)`).bind(`channel:${id}`,id).run();
  return send(env,id,r.meta.changes?"Подписка подтверждена. Начислено +5 ✨.":"Начисление уже проведено; баланс не изменён.");
}
